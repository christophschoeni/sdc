"""sdc secrets: SOPS + age. init, edit, pull, check, rekey. Plaintext never touches git."""
import os
import re
import shutil
import subprocess
from pathlib import Path

import yaml

HELP = "Secrets mit SOPS + age: init · set · edit · pull · check · rekey"
AGE_PUB = re.compile(r"^age1[0-9a-z]{58}$")
PLACEHOLDER = "REPLACE_WITH"


def register(p):
    p.add_argument("action", choices=["init", "set", "edit", "pull", "check", "rekey"])
    p.add_argument("name", nargs="?", help="set: Name des Secrets, z.B. HCLOUD_TOKEN")
    p.add_argument("--env", default="prod", help="dev | staging | prod (Standard: prod)")
    p.add_argument("--value-from-stdin", action="store_true", help="set: Wert von stdin lesen statt verdeckt abfragen")
    p.add_argument("--path", default=".", help="App-Ordner (Standard: .)")
    p.add_argument("--yes", action="store_true", help="pull: bestehende .env überschreiben")


# ---------- helpers ----------

def age_key_file() -> Path:
    return Path(os.environ.get("SOPS_AGE_KEY_FILE", Path.home() / ".config" / "sops" / "age" / "keys.txt"))


def local_public_key() -> str | None:
    f = age_key_file()
    if not f.exists():
        return None
    for line in f.read_text().splitlines():
        if line.startswith("# public key: "):
            return line.split(": ", 1)[1].strip()
    return None


def load_recipients(app: Path) -> list[dict]:
    f = app / "secrets" / "recipients.yml"
    if not f.exists():
        raise FileNotFoundError(f"fehlt: {f}")
    return (yaml.safe_load(f.read_text()) or {}).get("recipients", [])


def project_name(app: Path) -> str:
    m = yaml.safe_load((app / "schoeni.yaml").read_text())
    return m["project"]


def enc_path(app: Path, env: str) -> Path:
    return app / "secrets" / project_name(app) / f"{env}.enc.env"


def recipients_in_file(enc: Path) -> set[str]:
    return set(re.findall(r"sops_age__list_\d+__map_recipient=(age1[0-9a-z]+)", enc.read_text()))


def keys_of_dotenv(text: str) -> set[str]:
    return {m.group(1) for m in re.finditer(r"^([A-Z][A-Z0-9_]*)=", text, re.M) if not m.group(1).startswith("SOPS_")}


def sops(*args, **kw) -> subprocess.CompletedProcess:
    exe = shutil.which("sops")
    if not exe:
        raise RuntimeError("sops nicht installiert (brew install sops)")
    return subprocess.run([exe, *args], text=True, **kw)


# ---------- actions ----------

def do_init(app: Path) -> int:
    recs = load_recipients(app)
    pub = local_public_key()
    changed = False
    for r in recs:
        if r.get("role") == "owner" and str(r.get("age", "")).startswith(PLACEHOLDER) and pub:
            r["age"] = pub
            changed = True
    if changed:
        (app / "secrets" / "recipients.yml").write_text(
            "# generated owner key by sdc secrets init; rules: decision 0015\n" + yaml.safe_dump({"recipients": recs}, sort_keys=False))
    valid = [r for r in recs if AGE_PUB.match(str(r.get("age", "")))]
    if not valid:
        raise ValueError("kein gültiger Empfänger in secrets/recipients.yml")
    keys = "\n".join(f"  - &{r['name']} {r['age']}" for r in valid)
    refs = "\n".join(f"          - *{r['name']}" for r in valid)
    (app / ".sops.yaml").write_text(
        "# GENERATED by `sdc secrets init` from secrets/recipients.yml. Do not edit.\n"
        f"keys:\n{keys}\ncreation_rules:\n  - path_regex: secrets/.*\\.(enc\\.env|enc\\.yaml)$\n    key_groups:\n      - age:\n{refs}\n")
    missing = [r["name"] for r in recs if r not in valid]
    print(f".sops.yaml geschrieben: {len(valid)} Empfänger" + (f"; ohne gültigen Schlüssel: {', '.join(missing)}" if missing else ""))
    if len(valid) < 2:
        print("WARNUNG: nur ein Empfänger. Zweiten (Recovery-Schlüssel) anlegen: age-keygen, öffentlichen Teil eintragen, privaten auf Papier + Tresor.")
    return 0 if len(valid) >= 1 else 1


def ensure_enc(app: Path, env: str) -> Path:
    """Create an encrypted, empty dotenv file if none exists yet."""
    enc = enc_path(app, env)
    enc.parent.mkdir(parents=True, exist_ok=True)
    if not enc.exists():
        enc.write_text(f"SDC_CREATED={env}\n")
        r = sops("-e", "-i", "--input-type", "dotenv", "--output-type", "dotenv", str(enc), cwd=app, capture_output=True)
        if r.returncode:
            enc.unlink(missing_ok=True)
            raise RuntimeError(f"anlegen fehlgeschlagen: {r.stderr.strip()}")
    return enc


def do_edit(app: Path, env: str) -> int:
    enc = ensure_enc(app, env)
    return sops(str(enc), cwd=app).returncode


def do_set(app: Path, env: str, name: str | None, from_stdin: bool) -> int:
    import getpass
    import json
    import sys
    if not name or not re.match(r"^[A-Z][A-Z0-9_]*$", name):
        raise ValueError("Name fehlt oder ungültig, z.B. sdc secrets set HCLOUD_TOKEN")
    value = sys.stdin.readline().rstrip("\n") if from_stdin else getpass.getpass(f"{name} (Eingabe bleibt unsichtbar): ")
    if not value:
        raise ValueError("leerer Wert, nichts gespeichert")
    enc = ensure_enc(app, env)
    r = sops("set", str(enc), f'["{name}"]', json.dumps(value), cwd=app, capture_output=True)
    if r.returncode:
        raise RuntimeError(f"speichern fehlgeschlagen: {r.stderr.strip()}")
    print(f"{name} gespeichert in {enc.relative_to(app)} ({len(value)} Zeichen, verschlüsselt)")
    return 0


def decrypt(app: Path, enc: Path) -> str:
    r = sops("-d", "--input-type", "dotenv", "--output-type", "dotenv", str(enc), cwd=app, capture_output=True)
    if r.returncode:
        raise RuntimeError(f"entschlüsseln fehlgeschlagen: {r.stderr.strip()}")
    return r.stdout


def do_pull(app: Path, env: str, yes: bool) -> int:
    enc = enc_path(app, env)
    if not enc.exists():
        raise FileNotFoundError(f"fehlt: {enc} — zuerst `sdc secrets edit {env}`")
    target = app / ".env"
    if target.exists() and not yes:
        raise FileExistsError(".env existiert; mit --yes überschreiben")
    target.write_text(decrypt(app, enc))
    target.chmod(0o600)
    print(f".env geschrieben aus {enc.relative_to(app)} ({len(keys_of_dotenv(target.read_text()))} Werte)")
    return 0


def do_check(app: Path, env: str) -> int:
    problems: list[str] = []
    recs = load_recipients(app)
    bound = {r["age"] for r in recs if AGE_PUB.match(str(r.get("age", "")))}
    if any(str(r.get("age", "")).startswith(PLACEHOLDER) for r in recs):
        problems.append("recipients.yml enthält Platzhalter")
    if len(bound) < 2:
        problems.append("weniger als zwei Empfänger (Bus-Faktor)")
    sops_yaml = app / ".sops.yaml"
    if not sops_yaml.exists():
        problems.append(".sops.yaml fehlt — sdc secrets init")
    else:
        in_sops = set(re.findall(r"(age1[0-9a-z]{58})", sops_yaml.read_text()))
        if bound - in_sops:
            problems.append(f".sops.yaml fehlt Empfänger: {', '.join(sorted(bound - in_sops))}")
        if in_sops - bound:
            problems.append(f".sops.yaml hat Empfänger, die nicht in recipients.yml stehen: {', '.join(sorted(in_sops - bound))}")
    kf = age_key_file()
    if kf.exists() and (kf.stat().st_mode & 0o077):
        problems.append(f"age-Schlüssel zu offen: chmod 600 {kf}")
    for tracked in (".env",):
        r = subprocess.run(["git", "ls-files", "--error-unmatch", tracked], cwd=app, capture_output=True, text=True)
        if r.returncode == 0:
            problems.append(f"{tracked} ist im Git — sofort entfernen und Secrets rotieren")
    for enc in sorted((app / "secrets").glob("*/*.enc.env")):
        have = recipients_in_file(enc)
        if bound - have:
            problems.append(f"{enc.relative_to(app)}: nicht für alle Empfänger verschlüsselt — sdc secrets rekey")
        if "ENC[" not in enc.read_text():
            problems.append(f"{enc.relative_to(app)}: enthält keine verschlüsselten Werte")
    req_file = app / "config" / "secrets.required.yml"
    enc = enc_path(app, env)
    if req_file.exists() and enc.exists():
        required = set((yaml.safe_load(req_file.read_text()) or {}).get("required", []))
        try:
            present = keys_of_dotenv(decrypt(app, enc))
            missing = required - present
            if missing:
                problems.append(f"{enc.relative_to(app)} fehlt: {', '.join(sorted(missing))}")
        except RuntimeError as exc:
            problems.append(str(exc))
    for p in problems:
        print(f"[FEHLT] {p}")
    print("Secrets in Ordnung" if not problems else f"{len(problems)} Punkt(e) offen")
    return 0 if not problems else 1


def do_rekey(app: Path) -> int:
    rc = 0
    for enc in sorted((app / "secrets").glob("*/*.enc.*")):
        r = sops("updatekeys", "-y", str(enc), cwd=app)
        rc |= r.returncode
        print(f"{'ok' if r.returncode == 0 else 'FEHLER'}: {enc.relative_to(app)}")
    return rc


def run(args) -> int:
    app = Path(args.path).resolve()
    if args.action == "init":
        return do_init(app)
    if args.action == "set":
        return do_set(app, args.env, args.name, args.value_from_stdin)
    if args.action == "edit":
        return do_edit(app, args.env)
    if args.action == "pull":
        return do_pull(app, args.env, args.yes)
    if args.action == "check":
        return do_check(app, args.env)
    return do_rekey(app)
